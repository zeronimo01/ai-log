create table if not exists public.entries (
    id          bigint generated by default as identity primary key,
    day         date        not null,
    title       text        not null,
    learned     text        not null default '',
    executed    text        not null default '',
    result      text        not null default '',
    status      text        not null default 'success'
                check (status in ('success', 'partial', 'fail')),
    tags        text[]      not null default '{}',
    minutes     integer     not null default 0 check (minutes >= 0),
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

create index if not exists entries_day_idx on public.entries (day desc, id desc);

-- 보안: RLS를 켜고 정책을 만들지 않으면 공개(publishable/anon) 키로는 읽기·쓰기가 막히고,
-- 서버에 둔 secret 키로만 접근할 수 있습니다.
alter table public.entries enable row level security;
revoke all on public.entries from anon, authenticated;
grant select, insert, update, delete on public.entries to service_role;
grant usage, select on all sequences in schema public to service_role;

-- API 스키마 캐시 갱신 (테이블을 바로 인식하도록)
notify pgrst, 'reload schema';
